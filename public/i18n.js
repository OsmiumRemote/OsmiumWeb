let currentLocale = "zh-CN";

export function resolveLocale(pref) {
    if (pref === "zh-CN" || pref === "en-US") return pref;
    const nav = (typeof navigator !== "undefined" && (navigator.language || (Array.isArray(navigator.languages) ? navigator.languages[0] : ""))) || "zh-CN";
    return /^zh/i.test(nav) ? "zh-CN" : "en-US";
}

export function setLocale(pref) {
    currentLocale = resolveLocale(pref);
    if (typeof document !== "undefined" && document.documentElement) {
        document.documentElement.lang = currentLocale;
    }
    return currentLocale;
}

export function getLocale() {
    return currentLocale;
}

export function t(key, vars = null) {
    const dict = STRINGS[currentLocale] || STRINGS["zh-CN"];
    let text = Object.prototype.hasOwnProperty.call(dict, key)
        ? dict[key]
        : (STRINGS["zh-CN"][key] || key);
    if (vars && typeof vars === "object") {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

export function applyI18nToDom() {
    if (typeof document === "undefined") return;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        el.setAttribute("title", t(el.dataset.i18nTitle));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
        el.setAttribute("aria-label", t(el.dataset.i18nAria));
    });
}
